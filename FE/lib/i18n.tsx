interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, fallback?: string) => string;
}

const Ctx = createContext<LangCtx>({ lang: "id", setLang: () => {}, t: (k, fb) => fb ?? k });

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("id");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("app-lang") as Lang | null;
      if (saved === "id" || saved === "en") setLangState(saved);
      const settings = localStorage.getItem("appSettings");
      if (settings) {
        const parsed = JSON.parse(settings);
        if (parsed?.lang === "en" || parsed?.lang === "id") setLangState(parsed.lang);
      }
    } catch {}
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("app-lang", l);
      const raw = localStorage.getItem("appSettings");
      const parsed = raw ? JSON.parse(raw) : {};
      localStorage.setItem("appSettings", JSON.stringify({ ...parsed, lang: l }));
      window.dispatchEvent(new CustomEvent("language-changed", { detail: l }));
    } catch {}
  }, []);

  const t = useCallback(
    (key: string, fallback?: string) => STRINGS[lang][key] ?? STRINGS.id[key] ?? fallback ?? key,
    [lang]
  );

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useLanguage = () => useContext(Ctx);
